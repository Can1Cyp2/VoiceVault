-- ============================================================================
-- ADMIN RPC: get most-saved songs across all users
-- ============================================================================
CREATE OR REPLACE FUNCTION public.admin_get_most_saved_songs()
RETURNS TABLE (
  song_name TEXT,
  artist TEXT,
  save_count BIGINT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN QUERY
    SELECT ss.name::TEXT, ss.artist::TEXT, COUNT(*)::BIGINT AS save_count
    FROM public.saved_songs ss
    GROUP BY ss.name, ss.artist
    ORDER BY save_count DESC
    LIMIT 50;
END;
$$;
